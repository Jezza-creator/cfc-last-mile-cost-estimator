WITH
ORDERS AS (
    SELECT
        ORDER_ATTRIBUTE__ORDER_INVOICE_NUMBER                        AS INVOICE_NUMBER,
        ORDER_TRACKING_EVENT_2_DESPATCH_IN_PROGRESS__TIMESTAMP::DATE AS DESPATCH_DATE,
        ORDER_LOCATION__DELIVERY_SUBURB                              AS DEST_SUBURB,
        ORDER_LOCATION__DELIVERY_STATE                               AS DEST_STATE,
        ORDER_LOCATION__DELIVERY_POSTCODE::NUMBER                    AS DEST_POSTCODE,
        CARRIER_ATTRIBUTE__CARRIER_SERVICE_NAME                      AS ACTUAL_CARRIER,
        GREATEST(
            ORDER_WEIGHT__DEAD_WEIGHT,
            ORDER_WEIGHT__VOLUMETRIC_WEIGHT
        )                                                            AS CHARGEABLE_KG,
        ORDER_WEIGHT__DEAD_WEIGHT                                    AS DEAD_WEIGHT_KG,
        ORDER_PARCEL__PARCEL_COUNT                                   AS PARCEL_COUNT,
        ORDER_PRODUCT__PRODUCT_COUNT                                 AS SHIPPED_UNITS,
        ORDER_CARRIER__QUOTED_SHIPPING_COST_INCL_GST                 AS QUOTED_COST_INC_GST
    FROM KSFPA.FREIGHT.SHIPPIT_ORDERS
    WHERE STORE_ATTRIBUTE__STORE_NAME = '1194 Moorebank CFC NSW AU'
      AND ORDER_TRACKING_EVENT_2_DESPATCH_IN_PROGRESS__TIMESTAMP >= DATEADD(DAY, -7, CURRENT_DATE())
      AND ORDER_WEIGHT__DEAD_WEIGHT IS NOT NULL
      AND ORDER_WEIGHT__VOLUMETRIC_WEIGHT IS NOT NULL
),

-- Zone lookups are order-level, not postcode-level, to resolve multi-zone postcodes.
-- Priority: (1) exact suburb match, (2) non-REM zone, (3) any remaining zone.
AP_DEST_ZONE AS (
    SELECT
        O.INVOICE_NUMBER,
        PZ.ZONE_CODE AS AP_ZONE
    FROM ORDERS O
    JOIN KSFPA.ONLINE_PVT.LM_POSTCODE_ZONE PZ
      ON PZ.POSTCODE = O.DEST_POSTCODE
     AND PZ.CARRIER = 'Australia Post'
     AND PZ.MAPPING_VERSION = 'AP_9_ZONE_20250805'
     AND PZ.MAPPING_STATUS = 'ACTIVE'
     AND PZ.DESTINATION_ELIGIBLE = TRUE
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY O.INVOICE_NUMBER
        ORDER BY
            IFF(UPPER(TRIM(PZ.SUBURB)) = UPPER(TRIM(O.DEST_SUBURB)), 0, 1),
            IFF(PZ.ZONE_CODE = 'REM', 1, 0)
    ) = 1
),
ALLIED_DEST_ZONE AS (
    SELECT
        O.INVOICE_NUMBER,
        PZ.ZONE_CODE AS ALLIED_ZONE
    FROM ORDERS O
    JOIN KSFPA.ONLINE_PVT.LM_POSTCODE_ZONE PZ
      ON PZ.POSTCODE = O.DEST_POSTCODE
     AND PZ.CARRIER = 'Allied Express'
     AND PZ.MAPPING_VERSION = 'ALLIED_ZONE_GUIDE_CONDENSED'
     AND PZ.MAPPING_STATUS = 'ACTIVE'
     AND PZ.DESTINATION_ELIGIBLE = TRUE
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY O.INVOICE_NUMBER
        ORDER BY
            IFF(UPPER(TRIM(PZ.SUBURB)) = UPPER(TRIM(O.DEST_SUBURB)), 0, 1),
            IFF(PZ.ZONE_CODE = 'REM', 1, 0)
    ) = 1
),
CP_DEST_ZONE AS (
    SELECT
        O.INVOICE_NUMBER,
        PZ.ZONE_CODE AS CP_ZONE
    FROM ORDERS O
    JOIN KSFPA.ONLINE_PVT.LM_POSTCODE_ZONE PZ
      ON PZ.POSTCODE = O.DEST_POSTCODE
     AND PZ.CARRIER = 'Couriers Please'
     AND PZ.MAPPING_VERSION = 'NOVEMBER_2023_FINAL'
     AND PZ.MAPPING_STATUS = 'ACTIVE'
     AND PZ.DESTINATION_ELIGIBLE = TRUE
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY O.INVOICE_NUMBER
        ORDER BY
            IFF(UPPER(TRIM(PZ.SUBURB)) = UPPER(TRIM(O.DEST_SUBURB)), 0, 1),
            IFF(PZ.ZONE_CODE = 'REM', 1, 0)
    ) = 1
),
ALLIED_EST AS (
    SELECT
        O.INVOICE_NUMBER,
        'Allied Express' AS CARRIER,
        'Allied Express' AS SERVICE,
        GREATEST(
            LR.MINIMUM_CHARGE_EX_GST,
            LR.BASIC_CHARGE_EX_GST + O.CHARGEABLE_KG * LR.PER_KG_RATE_EX_GST
        ) AS EST_COST
    FROM ORDERS O
    JOIN ALLIED_DEST_ZONE DZ
      ON DZ.INVOICE_NUMBER = O.INVOICE_NUMBER
    JOIN KSFPA.ONLINE_PVT.LM_LANE_RATE LR
      ON LR.RATECARD_ID = 'ALLIED_ECOM_20260706'
     AND LR.ORIGIN_ZONE = 'N01'
     AND LR.DESTINATION_ZONE = DZ.ALLIED_ZONE
),
CP_EST AS (
    SELECT
        O.INVOICE_NUMBER,
        'Couriers Please' AS CARRIER,
        'Couriers Please' AS SERVICE,
        GREATEST(
            LR.MINIMUM_CHARGE_EX_GST,
            LR.BASIC_CHARGE_EX_GST + O.CHARGEABLE_KG * LR.PER_KG_RATE_EX_GST
        ) AS EST_COST
    FROM ORDERS O
    JOIN CP_DEST_ZONE DZ
      ON DZ.INVOICE_NUMBER = O.INVOICE_NUMBER
    JOIN KSFPA.ONLINE_PVT.LM_LANE_RATE LR
      ON LR.RATECARD_ID = 'CP_I99_20260504'
     AND LR.ORIGIN_ZONE = 'SYD'
     AND LR.DESTINATION_ZONE = DZ.CP_ZONE
),
GOEXPRESS_EST AS (
    SELECT
        O.INVOICE_NUMBER,
        'GoPeople' AS CARRIER,
        'GoEXPRESS' AS SERVICE,
        WB.BAND_RATE_EX_GST AS EST_COST
    FROM ORDERS O
    JOIN AP_DEST_ZONE DZ
      ON DZ.INVOICE_NUMBER = O.INVOICE_NUMBER
    JOIN KSFPA.ONLINE_PVT.LM_WEIGHT_BAND WB
      ON WB.RATECARD_ID = 'GOPEOPLE_GOEXPRESS_20260615'
     AND WB.ORIGIN_ZONE = 'Sydney'
     AND WB.DESTINATION_ZONE = DZ.AP_ZONE
     AND O.CHARGEABLE_KG >= WB.MIN_WEIGHT_KG
     AND O.CHARGEABLE_KG < WB.MAX_WEIGHT_KG
),
AP_EST AS (
    -- AP eParcel <= 5 kg: flat weight-band rate.
    -- Uses LM_SERVICE_COVERAGE (Sydney origin) to resolve AP zone to pricing category.
    SELECT
        O.INVOICE_NUMBER,
        'Australia Post' AS CARRIER,
        'eParcel' AS SERVICE,
        WB.BAND_RATE_EX_GST AS EST_COST
    FROM ORDERS O
    JOIN AP_DEST_ZONE DZ
      ON DZ.INVOICE_NUMBER = O.INVOICE_NUMBER
    JOIN KSFPA.ONLINE_PVT.LM_SERVICE_COVERAGE SC
      ON SC.RATECARD_ID = 'AP_EPARCEL_20250805'
     AND SC.ORIGIN_AREA = 'Sydney'
     AND SC.DESTINATION_AREA = DZ.AP_ZONE
     AND SC.COVERAGE_ACTION = 'INCLUDE'
    JOIN KSFPA.ONLINE_PVT.LM_WEIGHT_BAND WB
      ON WB.RATECARD_ID = 'AP_EPARCEL_20250805'
     AND WB.ORIGIN_ZONE = 'Sydney'
     AND O.CHARGEABLE_KG >= WB.MIN_WEIGHT_KG
     AND O.CHARGEABLE_KG < WB.MAX_WEIGHT_KG
     AND WB.DESTINATION_ZONE = SC.DESTINATION_ZONE
    WHERE O.CHARGEABLE_KG <= 5.0
),
AP_LANE_EST AS (
    -- AP eParcel > 5 kg and <= 22 kg: formula-based via LM_SERVICE_COVERAGE to LM_LANE_RATE.
    -- ORIGIN_AREA = 'Sydney' (Moorebank CFC). DESTINATION_AREA = AP postcode zone code.
    SELECT
        O.INVOICE_NUMBER,
        'Australia Post' AS CARRIER,
        'eParcel' AS SERVICE,
        (
            LR.FIRST_PARCEL_RATE_EX_GST
            + LR.PER_KG_RATE_EX_GST * CEIL(O.CHARGEABLE_KG / NULLIF(O.PARCEL_COUNT, 0))
        )
        + GREATEST(O.PARCEL_COUNT - 1, 0)
            * (
                LR.SUBSEQUENT_PARCEL_RATE_EX_GST
                + LR.PER_KG_RATE_EX_GST * CEIL(O.CHARGEABLE_KG / NULLIF(O.PARCEL_COUNT, 0))
            ) AS EST_COST
    FROM ORDERS O
    JOIN AP_DEST_ZONE DZ
      ON DZ.INVOICE_NUMBER = O.INVOICE_NUMBER
    JOIN KSFPA.ONLINE_PVT.LM_SERVICE_COVERAGE SC
      ON SC.RATECARD_ID = 'AP_EPARCEL_20250805'
     AND SC.ORIGIN_AREA = 'Sydney'
     AND SC.DESTINATION_AREA = DZ.AP_ZONE
     AND SC.COVERAGE_ACTION = 'INCLUDE'
    JOIN KSFPA.ONLINE_PVT.LM_LANE_RATE LR
      ON LR.RATECARD_ID = 'AP_EPARCEL_20250805'
     AND TRIM(LR.DESTINATION_ZONE) = TRIM(SC.DESTINATION_ZONE)
     AND LR.RATE_LINE_ID LIKE 'AP_EPARCEL_OVER5_%'
    WHERE O.CHARGEABLE_KG > 5.0
      AND O.CHARGEABLE_KG <= 22.0
),
ALL_EST AS (
    SELECT * FROM ALLIED_EST
    UNION ALL
    SELECT * FROM CP_EST
    UNION ALL
    SELECT * FROM GOEXPRESS_EST
    UNION ALL
    SELECT * FROM AP_EST
    UNION ALL
    SELECT INVOICE_NUMBER, CARRIER, SERVICE, EST_COST FROM AP_LANE_EST
),
ACTUAL_EST AS (
    SELECT
        O.INVOICE_NUMBER,
        MAX(AE.EST_COST) AS ACTUAL_EST_COST
    FROM ORDERS O
    LEFT JOIN ALL_EST AE
      ON AE.INVOICE_NUMBER = O.INVOICE_NUMBER
     AND AE.SERVICE = CASE
                         WHEN O.ACTUAL_CARRIER = 'eParcel Metro' THEN 'eParcel'
                         ELSE O.ACTUAL_CARRIER
                      END
    GROUP BY O.INVOICE_NUMBER
),
CHEAPEST_ALT AS (
    SELECT
        AE.INVOICE_NUMBER,
        FIRST_VALUE(AE.CARRIER) OVER (
            PARTITION BY AE.INVOICE_NUMBER
            ORDER BY AE.EST_COST
        ) AS ALT_CARRIER,
        FIRST_VALUE(AE.SERVICE) OVER (
            PARTITION BY AE.INVOICE_NUMBER
            ORDER BY AE.EST_COST
        ) AS ALT_SERVICE,
        MIN(AE.EST_COST) OVER (
            PARTITION BY AE.INVOICE_NUMBER
        ) AS ALT_COST
    FROM ALL_EST AE
    JOIN ORDERS O
      ON O.INVOICE_NUMBER = AE.INVOICE_NUMBER
     AND AE.SERVICE != O.ACTUAL_CARRIER
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY AE.INVOICE_NUMBER
        ORDER BY AE.EST_COST
    ) = 1
)
SELECT
    O.INVOICE_NUMBER,
    O.DESPATCH_DATE,
    O.DEST_SUBURB,
    O.DEST_STATE,
    O.DEST_POSTCODE,
    O.CHARGEABLE_KG,
    CASE
        WHEN O.CHARGEABLE_KG <= 0.5 THEN 'Up to 0.5 kg'
        WHEN O.CHARGEABLE_KG <= 1.0 THEN 'Over 0.5 kg to 1 kg'
        WHEN O.CHARGEABLE_KG <= 3.0 THEN 'Over 1 kg to 3 kg'
        WHEN O.CHARGEABLE_KG <= 5.0 THEN 'Over 3 kg to 5 kg'
        WHEN O.CHARGEABLE_KG <= 20.0 THEN 'Over 5 kg to 20 kg'
        WHEN O.CHARGEABLE_KG <= 22.0 THEN 'Over 20 kg to 22 kg'
        ELSE 'Over 22 kg'
    END AS WEIGHT_CLASS,
    O.DEAD_WEIGHT_KG,
    CASE
        WHEN O.DEAD_WEIGHT_KG <= 0.5 THEN 'Up to 0.5 kg'
        WHEN O.DEAD_WEIGHT_KG <= 1.0 THEN 'Over 0.5 kg to 1 kg'
        WHEN O.DEAD_WEIGHT_KG <= 3.0 THEN 'Over 1 kg to 3 kg'
        WHEN O.DEAD_WEIGHT_KG <= 5.0 THEN 'Over 3 kg to 5 kg'
        WHEN O.DEAD_WEIGHT_KG <= 20.0 THEN 'Over 5 kg to 20 kg'
        WHEN O.DEAD_WEIGHT_KG <= 22.0 THEN 'Over 20 kg to 22 kg'
        ELSE 'Over 22 kg'
    END AS DEAD_WEIGHT_CLASS,
    O.PARCEL_COUNT,
    O.SHIPPED_UNITS,
    O.ACTUAL_CARRIER,
    O.QUOTED_COST_INC_GST,
    ROUND(AC.ACTUAL_EST_COST, 2) AS ACTUAL_EST_COST_EX_GST,
    CA.ALT_CARRIER AS CHEAPEST_ALT_CARRIER,
    CA.ALT_SERVICE AS CHEAPEST_ALT_SERVICE,
    ROUND(CA.ALT_COST, 2) AS CHEAPEST_ALT_COST_EX_GST,
    IFF(
        AC.ACTUAL_EST_COST IS NOT NULL
        AND CA.ALT_COST IS NOT NULL,
        ROUND(AC.ACTUAL_EST_COST - CA.ALT_COST, 2),
        NULL
    ) AS EST_SAVING_EX_GST,
    IFF(
        AC.ACTUAL_EST_COST IS NOT NULL
        AND CA.ALT_COST IS NOT NULL
        AND AC.ACTUAL_EST_COST - CA.ALT_COST > 0,
        'Y',
        NULL
    ) AS CHEAPER_OPTION_EXISTS
FROM ORDERS O
LEFT JOIN ACTUAL_EST AC
  ON AC.INVOICE_NUMBER = O.INVOICE_NUMBER
LEFT JOIN CHEAPEST_ALT CA
  ON CA.INVOICE_NUMBER = O.INVOICE_NUMBER
ORDER BY O.DESPATCH_DATE DESC, EST_SAVING_EX_GST DESC NULLS LAST;
